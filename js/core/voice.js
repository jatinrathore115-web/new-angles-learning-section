/* Narration voice-over player.
   Clips live in assets/vo/<id>.ogg (Ogg Opus) with a .caf twin (the same Opus audio
   for Safari/iOS builds that cannot play Ogg). They are looked up by the exact plain
   text the narration line shows (js/vo_lines.js, generated by tools/vo_build.mjs),
   together with where the narrator actually speaks and pauses (tools/vo_timing.mjs).

   The VOICE IS THE CLOCK: speak() returns a handle whose clock() reads the clip's own
   playback position, so the words on screen, the spoken-word highlight and the geometry
   cues follow the voice even when a clip starts late on a slow network or stalls.
   speak() resolves when the clip ends. A line with no clip, or any audio failure,
   falls back to silent typing at reading pace — the lesson never stalls. */
(function () {
  const q = new URLSearchParams(location.search);
  const RATE = Math.min(4, Math.max(0.5, +q.get('speed') || 1));   // debug speed → playbackRate
  // vo_lines.js declares a top-level const (a global binding, not a window property)
  const LINES = typeof VO_LINES !== 'undefined' ? VO_LINES : {};
  const audio = new Audio();
  audio.preload = 'auto';
  audio.setAttribute('playsinline', '');
  // Ogg Opus where the browser plays it; otherwise the Core Audio twin (Safari / iOS)
  const EXT = audio.canPlayType('audio/ogg; codecs="opus"') ? 'ogg'
    : audio.canPlayType('audio/x-caf; codecs="opus"') || audio.canPlayType('audio/x-caf') ? 'caf' : null;
  let enabled = !!EXT && q.get('vo') !== '0';
  let cur = null;      // the line being spoken (a handle, see speak)
  let last = null;     // plain text of the line spoken last (not repeated back-to-back)
  const blobs = {};    // clip id → object URL of a prefetched clip (http/https only)

  const plain = text => String(text).replace(/[*|]/g, '').replace(/\s+/g, ' ').trim();
  const clip = p => { const c = LINES[p]; return c ? { id: c[0], sec: c[1], on: c[2], off: c[3], gaps: c[4] || [] } : null; };
  const url = id => blobs[id] || `assets/vo/${id}.${EXT}`;
  const now = () => performance.now();

  /** reading-time estimate for lines typed silently */
  function estimate(text) {
    const words = plain(text).split(/\s+/).length;
    return Math.max(1100, words * 300 + 450);
  }

  /** letters a word takes to say aloud: "90°" is "ninety degrees", "∠1" "angle one",
      "OA" "oh ay" — so numbers and symbols get their real share of the clip */
  const ONES = [0, 3, 3, 5, 4, 4, 3, 5, 5, 4, 3, 6, 6, 8, 8, 7, 7, 9, 8, 8];
  const TENS = [0, 0, 6, 6, 5, 5, 5, 7, 6, 6];
  const numLen = n => n < 20 ? (ONES[n] || 4) : n < 100 ? TENS[n / 10 | 0] + (n % 10 ? 1 + ONES[n % 10] : 0)
    : ONES[n / 100 | 0] + 8 + (n % 100 ? 4 + numLen(n % 100) : 0);
  function spokenLen(word) {
    let s = word.replace(/[.,;:?!’'"“”()]/g, ''), len = 0;
    s = s.replace(/\d+/g, d => { len += numLen(+d) + 1; return ''; });
    len += (s.match(/°/g) || []).length * 8 + (s.match(/∠/g) || []).length * 6 + (s.match(/[=+−]/g) || []).length * 6;
    s = s.replace(/[°∠=+−—]/g, '');
    len += /^[A-Z]{2,3}$/.test(s) ? s.length * 3 : s.length;            // OA, OB, AOB are spelled out
    return Math.max(1, len);
  }

  /** start time (ms on the line's clock) of every word, from the measured speech:
      the clip's pauses are matched, in order, to the word gaps that carry punctuation
      (or any gap, if the narrator paused there), and words between two anchors are
      spread by how long they take to say. Without measurements the whole clip is spread.
      strong: a word boundary that should take a pause if the narrator made one (a chunk break). */
  function wordTimes(c, words, strong = -1) {
    const n = words.length, w = words.map(x => spokenLen(x) + 1);
    const total = w.reduce((a, b) => a + b, 0) || 1;
    const on = c.on ?? 0.14, off = c.off ?? Math.max(on + 0.3, c.sec - 0.35);
    const cum = [0]; for (const x of w) cum.push(cum[cum.length - 1] + x);
    const est = j => on + (cum[j + 1] / total) * (off - on);             // estimated end of word j
    const punct = j => j === strong || /[,.;:?!—]$/.test(words[j]) || words[j + 1] === '—';
    // monotone DP: gaps g[k] ↔ word boundaries j (after word j); unmatched gaps fall inside words
    const g = (c.gaps || []).filter(x => x[0] > on && x[1] < off), K = g.length, J = n - 1;
    const INF = 1e9, span = off - on;
    const D = Array.from({ length: K + 1 }, () => new Float64Array(J + 1).fill(INF));
    const back = Array.from({ length: K + 1 }, () => new Int16Array(J + 1).fill(-1));
    for (let j = 0; j <= J; j++) D[0][j] = 0;
    for (let k = 1; k <= K; k++) {
      const [a, b] = g[k - 1], mid = (a + b) / 2, len = b - a;
      const skip = len > 0.22 ? 0.35 : 0.08;
      for (let j = 0; j <= J; j++) {
        // gap k left unmatched
        let best = D[k - 1][j] + skip, arg = -1;
        // gap k matched to boundary j-1 (after word j-1), boundaries strictly increasing
        if (j >= 1) {
          const bj = j - 1, cost = Math.abs(mid - est(bj)) / span * 2 - (punct(bj) ? 0.4 : 0) - Math.min(0.3, len);
          const prev = D[k - 1][j - 1] + cost;
          if (prev < best) { best = prev; arg = bj; }
        }
        // carry best of smaller j (boundary index free to advance)
        if (j >= 1 && D[k][j - 1] < best) { best = D[k][j - 1]; arg = -2; }
        D[k][j] = best; back[k][j] = arg;
      }
    }
    const anchor = new Map();                                          // boundary → gap
    for (let k = K, j = J; k > 0;) {
      const a = back[k][j];
      if (a === -2) { j--; continue; }
      if (a >= 0) { anchor.set(a, g[k - 1]); j = a; }
      k--;
    }
    // walk the words: segments between anchors are spread by length
    const t = new Array(n);
    let segStart = 0, segT = on;
    const bounds = [...anchor.keys()].sort((x, y) => x - y).concat([n - 1]);
    for (const bj of bounds) {
      const endT = bj === n - 1 && !anchor.has(bj) ? off : anchor.get(bj)[0];
      const chars = cum[bj + 1] - cum[segStart] || 1;
      for (let i = segStart; i <= bj; i++) t[i] = segT + (cum[i] - cum[segStart]) / chars * (endT - segT);
      if (anchor.has(bj)) { segT = anchor.get(bj)[1]; segStart = bj + 1; }
    }
    return { t: t.map(x => x * 1000), end: off * 1000, gaps: [...anchor.entries()].map(([j, gp]) => ({ after: j, from: gp[0] * 1000, to: gp[1] * 1000 })) };
  }

  /** a silent handle: typed at a calm narrator pace, resolves after reading time */
  function silent(p, wait) {
    const t0 = now();
    return { p, voiced: false, clock: () => (now() - t0) / Tween.TS, promise: wait ? Tween.sleep(estimate(p)) : Promise.resolve() };
  }

  /* one watchdog for the line being spoken: ends it when the clip ends, releases a
     held pause, and gives up on a clip that never starts or stops making progress */
  const START_LIMIT = 6000, STALL_LIMIT = 4000;
  Tween.onFrame(() => {
    const me = cur;
    if (!me || me.done) return;
    const t = now();
    if (me.hold && !me.held && !audio.paused && audio.currentTime >= me.hold.at) {
      me.held = true; audio.pause(); me.resumeAt = t + me.hold.ms * Tween.TS;
    }
    if (me.held && me.resumeAt && t >= me.resumeAt) { me.resumeAt = 0; me.lastMove = t; me.play(); }
    if (audio.ended) return me.finish();
    if (!me.started) { if (t - me.t0 > START_LIMIT) me.fail(); return; }
    if (audio.currentTime !== me.lastPos) { me.lastPos = audio.currentTime; me.lastMove = t; }
    else if (!me.resumeAt && t - me.lastMove > STALL_LIMIT) me.finish();
  });

  // a phone that locks, or a tab sent to the background, may pause the clip: on return
  // the line carries on from where it was (and is not mistaken for a stalled clip)
  document.addEventListener('visibilitychange', () => {
    const me = cur;
    if (document.hidden || !me || me.done || me.fallback) return;
    me.lastMove = now(); me.t0 = Math.max(me.t0, now() - 1000);
    if (audio.paused && !(me.held && me.resumeAt)) me.play();
  });

  const Voice = {
    plain, estimate,
    get audio() { return audio; },          // read-only, for playback tests
    get current() { return cur && cur.p; },
    get enabled() { return enabled; },
    set enabled(v) { enabled = !!v && !!EXT; if (!enabled) Voice.stop(); },
    get format() { return EXT; },

    /** word start times for a line ({ t:[ms], end, gaps }) on its clip's clock, or null if typed silently */
    timeline(text, words, strong = -1) { const c = enabled && clip(plain(text)); return c ? wordTimes(c, words, strong) : null; },

    /** say a line. Returns a handle { promise, clock(), voiced }:
        promise resolves when the clip ends (or after reading time when silent);
        clock() is the line's own time in ms (the clip's position while it plays).
        opts.hold = { at: ms on the clip, ms } pauses the voice there (between chunks). */
    speak(text, { force = false, hold = null } = {}) {
      const p = plain(text);
      if (!force && cur && cur.p === p) return cur;                       // already saying it: join, don't restart
      if (!force && !cur && last === p) return silent(p, false);          // just said it: don't repeat (unless replayed)
      Voice.stop(false);                                                   // a new line stops the previous voice
      const c = enabled ? clip(p) : null;
      if (!c) { last = p; return silent(p, true); }
      let resolve; const promise = new Promise(r => { resolve = r; });
      const me = { p, promise, voiced: true, t0: now(), started: false, lastMove: now(), lastPos: -1, done: false, fallback: null };
      me.hold = hold && hold.ms > 0 ? { at: hold.at / 1000, ms: hold.ms } : null;
      // the clip position, in ms; if the clip failed, a reading-pace clock takes over from where it was
      me.clock = () => me.fallback ? me.fallback.base + (now() - me.fallback.t) / Tween.TS
        : me.done ? Infinity : me.started ? audio.currentTime * 1000 : 0;
      me.play = () => { const pr = audio.play(); if (pr && pr.catch) pr.catch(() => cur === me && me.fail()); };
      me.finish = () => {
        if (me.done) return;
        me.done = true;
        if (cur === me) { cur = null; last = p; Sound.duck(false); }
        resolve();
      };
      // the clip cannot play: keep the words moving at reading pace, then finish
      me.fail = () => {
        if (me.done || me.fallback) return;
        const base = me.started ? audio.currentTime * 1000 : 0;
        me.fallback = { base, t: now() };
        if (cur === me) { cur = null; last = p; audio.pause(); Sound.duck(false); }
        Tween.sleep(Math.max(600, estimate(p) * (1 - base / (c.sec * 1000)))).then(() => { me.done = true; resolve(); });
      };
      cur = me;
      audio.onplaying = () => { if (cur === me && !me.started) { me.started = true; me.lastMove = now(); } };
      audio.onerror = () => cur === me && me.fail();
      audio.onended = () => cur === me && me.finish();
      audio.muted = false;
      audio.src = url(c.id);
      audio.defaultPlaybackRate = audio.playbackRate = RATE;
      Sound.duck(true);
      me.play();
      return me;
    },

    /** stop the voice. reset=true (screen change) also forgets the last line */
    stop(reset = true) {
      if (cur) { const f = cur.finish; cur.resumeAt = 0; audio.pause(); f(); cur = null; }
      if (reset) last = null;
    },

    /** call inside the first user gesture (Begin) so tablets allow later playback */
    unlock() {
      if (!enabled) return;
      const first = Object.values(LINES)[0];
      if (!first) return;
      audio.muted = true; audio.src = url(first[0]);
      const pr = audio.play();
      const done = () => { if (!cur) { audio.pause(); audio.muted = false; } };
      if (pr && pr.then) pr.then(done, done); else done();
    },

    /** warm every clip in lesson order. Over http(s) each clip is downloaded once and
        kept in memory, so later lines start at once even on a slow connection; from
        disk (file://) the browser cache is warmed instead. A few downloads run at once. */
    async prefetch() {
      if (!enabled) return;
      const ids = Object.values(LINES).map(v => v[0]);
      const web = /^https?:$/.test(location.protocol);
      const one = async id => {
        if (blobs[id]) return;
        if (web) {
          try {
            const r = await fetch(`assets/vo/${id}.${EXT}`);
            if (r.ok) blobs[id] = URL.createObjectURL(await r.blob());
          } catch (e) { /* the clip streams from the network when it is needed */ }
          return;
        }
        await new Promise(res => {
          const a = new Audio(); a.preload = 'auto';
          const t = setTimeout(res, 4000);
          a.oncanplaythrough = a.onerror = () => { clearTimeout(t); res(); };
          a.src = url(id); a.load();
        });
      };
      let i = 0;
      const worker = async () => { while (i < ids.length) await one(ids[i++]); };
      await Promise.all([worker(), worker(), worker()]);
    },
  };
  window.Voice = Voice;
})();
