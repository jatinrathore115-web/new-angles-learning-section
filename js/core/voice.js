/* Narration voice-over player.
   Clips live in assets/vo/<id>.ogg (Ogg Opus) and are looked up by the exact plain
   text the narration line shows (js/vo_lines.js, generated by tools/vo_build.mjs).
   VO is the timeline authority: speak() resolves when the clip ends, so animation
   beats wait for the words that describe them. A line with no clip, or any audio
   failure, falls back to silent typing at reading pace — the lesson never stalls. */
(function () {
  const q = new URLSearchParams(location.search);
  const RATE = Math.min(4, Math.max(0.5, +q.get('speed') || 1));   // debug speed → playbackRate
  // vo_lines.js declares a top-level const (a global binding, not a window property)
  const LINES = typeof VO_LINES !== 'undefined' ? VO_LINES : {};
  const audio = new Audio();
  audio.preload = 'auto';
  const SUPPORTED = !!audio.canPlayType('audio/ogg; codecs="opus"');
  let enabled = SUPPORTED && q.get('vo') !== '0';
  let cur = null;      // { p, promise, finish, timer } — the line being spoken
  let last = null;     // plain text of the line spoken last (not repeated back-to-back)

  const plain = text => String(text).replace(/\*/g, '');
  const clip = p => { const c = LINES[p]; return c ? { id: c[0], sec: c[1] } : null; };
  const url = id => `assets/vo/${id}.ogg`;

  /** reading-time estimate for lines typed silently */
  function estimate(text) {
    const words = plain(text).split(/\s+/).length;
    return Math.max(1100, words * 300 + 450);
  }

  const Voice = {
    plain, estimate,
    get audio() { return audio; },          // read-only, for playback tests
    get current() { return cur && cur.p; },
    get enabled() { return enabled; },
    set enabled(v) { enabled = !!v && SUPPORTED; if (!enabled) Voice.stop(); },

    /** seconds the line will take to say at the current rate, or null if it is typed silently */
    duration(text) { const c = enabled && clip(plain(text)); return c ? c.sec / RATE : null; },

    /** say a line; resolves when the clip ends (or immediately/after reading time when silent) */
    speak(text, { force = false } = {}) {
      const p = plain(text);
      if (!force && cur && cur.p === p) return cur.promise;   // already saying it: join, don't restart
      if (!force && !cur && last === p) return Promise.resolve();   // just said it: don't repeat (unless replayed)
      Voice.stop(false);                                       // a new line stops the previous voice
      const c = enabled ? clip(p) : null;
      if (!c) { last = p; return Tween.sleep(estimate(p)); }
      let resolve; const promise = new Promise(r => { resolve = r; });
      const me = { p, promise };
      me.finish = () => {
        if (me.done) return;
        me.done = true;
        clearTimeout(me.timer);
        if (cur === me) { cur = null; last = p; Sound.duck(false); }
        resolve();
      };
      cur = me;
      audio.onended = () => cur === me && me.finish();
      audio.onerror = () => cur === me && me.finish();
      audio.muted = false;
      audio.src = url(c.id);
      audio.defaultPlaybackRate = audio.playbackRate = RATE;
      // safety: a stalled clip can never lock the lesson
      me.timer = setTimeout(me.finish, (c.sec / RATE) * 1000 + 600 + 800);
      Sound.duck(true);
      const pr = audio.play();
      if (pr && pr.catch) pr.catch(() => cur === me && me.finish());
      return promise;
    },

    /** stop the voice. reset=true (screen change) also forgets the last line */
    stop(reset = true) {
      if (cur) { const f = cur.finish; cur = null; audio.pause(); Sound.duck(false); f(); }
      if (reset) last = null;
    },

    /** call inside the first user gesture (Begin) so tablets allow later playback */
    unlock() {
      if (!enabled) return;
      const first = Object.values(LINES)[0];
      if (!first) return;
      const u = url(first[0]);
      audio.muted = true; audio.src = u;
      const pr = audio.play();
      const done = () => { if (!cur) { audio.pause(); } audio.muted = false; };
      if (pr && pr.then) pr.then(done, done); else done();
    },

    /** warm every clip, one at a time, so each is ready when needed */
    async prefetch() {
      if (!enabled) return;
      for (const [id] of Object.values(LINES)) {
        await new Promise(res => {
          const a = new Audio(); a.preload = 'auto';
          const t = setTimeout(res, 4000);
          a.oncanplaythrough = a.onerror = () => { clearTimeout(t); res(); };
          a.src = url(id); a.load();
        });
      }
    },
  };
  window.Voice = Voice;
})();
